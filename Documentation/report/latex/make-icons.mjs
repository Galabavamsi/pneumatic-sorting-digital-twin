// Writes icons.tex: technology logos as TikZ vector paths, from an icons.json
// ({ slug: { title, path } }, 24x24 SVG path data from the simple-icons set).
//   node make-icons.mjs <icons.json>
import fs from 'node:fs';

const icons = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const cap = (s) => s.replace(/[^a-z]/g, '').replace(/^./, (c) => c.toUpperCase());
const B = String.fromCharCode(92);      // backslash
let out = '% Technology logos as vector paths (simple-icons set). Generated by make-icons.mjs; do not edit.\n';
out += '% Usage inside a tikzpicture: ' + B + 'icoDotnet{x}{y}{scale}. The icon is 24pt square, drawn down and right from (x,y).\n';
for (const [slug, icon] of Object.entries(icons)) {
  out += `${B}newcommand{${B}ico${cap(slug)}}[3]{${B}begin{scope}[shift={(#1,#2)},scale=#3,yscale=-1]${B}fill[ink] svg {${icon.path}};${B}end{scope}}\n`;
}
fs.writeFileSync('icons.tex', out);
console.log(Object.keys(icons).map(cap).join(' '));
